export const DEFAULT_LANGUAGE: UiLanguage = "zh-CN";

export function parseUiLanguage(value: unknown): UiLanguage {
  return value === "en-US" || value === "zh-CN" ? value : DEFAULT_LANGUAGE;
}

export function translate(language: UiLanguage, key: TranslationKey): string {
  return (language === "en-US" ? enUS[key] : zhCN[key]) ?? zhCN[key];
}

export function registeredMessageKeys(): string[] { return registeredContractMessageKeys(); }
export function translateRegisteredMessage(language: UiLanguage, key: string, parameters: SafeMessageParameters): string {
  const usage = key.startsWith("services.") ? "serviceHealth" : key.startsWith("reminders.") ? "reminderDisplay" : key === "home.agents.more" ? "uiDisplay" : "commandError";
  if (!validateMessageParameters(usage, key, parameters)) throw new Error("message contract violation");
  let text = messageCatalog.messages[key as keyof typeof messageCatalog.messages]?.[language];
  if (!text) throw new Error("unknown message key");
  for (const [name, value] of Object.entries(parameters)) {
    const rendered = name === "triggerStatus" ? messageCatalog.parameterEnums.triggerStatus[value as keyof typeof messageCatalog.parameterEnums.triggerStatus][language] : name === "metric" ? messageCatalog.parameterEnums.metric[value as keyof typeof messageCatalog.parameterEnums.metric][language] : String(value);
    text = text.replaceAll(`{${name}}`, rendered);
  }
  return text;
}
